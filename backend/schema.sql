-- =========================================================
-- PSO GAMING PLATFORM - SUPABASE POSTGRESQL SCHEMA DUMP
-- =========================================================

-- 1. Enable UUID extension if needed
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 2. USERS TABLE
CREATE TABLE IF NOT EXISTS users (
    id SERIAL PRIMARY KEY,
    auth_user_id VARCHAR(100) UNIQUE,
    player_id VARCHAR(50) UNIQUE NOT NULL,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(150) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    profile_photo TEXT,
    role VARCHAR(20) DEFAULT 'USER' NOT NULL, -- 'SUPER_ADMIN', 'ADMIN', 'USER'
    status VARCHAR(20) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 3. PLAYER RATINGS TABLE
CREATE TABLE IF NOT EXISTS player_ratings (
    id SERIAL PRIMARY KEY,
    player_id INTEGER REFERENCES users(id) ON DELETE CASCADE NOT NULL,
    game_mode VARCHAR(10) NOT NULL, -- '1V1', '2V2'
    rating DOUBLE PRECISION DEFAULT 1500.0 NOT NULL,
    matches_played INTEGER DEFAULT 0 NOT NULL,
    wins INTEGER DEFAULT 0 NOT NULL,
    losses INTEGER DEFAULT 0 NOT NULL,
    draws INTEGER DEFAULT 0 NOT NULL,
    win_rate DOUBLE PRECISION DEFAULT 0.0 NOT NULL,
    win_streak INTEGER DEFAULT 0 NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT unique_player_game_mode UNIQUE(player_id, game_mode)
);

-- 4. TEAMS TABLE
CREATE TABLE IF NOT EXISTS teams (
    id SERIAL PRIMARY KEY,
    name VARCHAR(100) UNIQUE NOT NULL,
    league VARCHAR(100) NOT NULL,
    ovr INTEGER DEFAULT 80 NOT NULL,
    atk INTEGER DEFAULT 80 NOT NULL,
    mid INTEGER DEFAULT 80 NOT NULL,
    "def" INTEGER DEFAULT 80 NOT NULL,
    category VARCHAR(50) DEFAULT 'Club' NOT NULL,
    status VARCHAR(20) DEFAULT 'ACTIVE' NOT NULL,
    logo_url VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 5. SEASONS TABLE
CREATE TABLE IF NOT EXISTS seasons (
    id SERIAL PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    start_date TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    end_date TIMESTAMP WITH TIME ZONE,
    status VARCHAR(20) DEFAULT 'ACTIVE' NOT NULL -- 'ACTIVE', 'UPCOMING', 'COMPLETED', 'ARCHIVED'
);

-- 6. MATCHES TABLE
CREATE TABLE IF NOT EXISTS matches (
    id SERIAL PRIMARY KEY,
    match_code VARCHAR(50) UNIQUE NOT NULL,
    game_mode VARCHAR(10) NOT NULL, -- '1V1', '2V2'
    season_id INTEGER REFERENCES seasons(id),
    status VARCHAR(30) DEFAULT 'WAITING' NOT NULL, -- 'WAITING', 'READY', 'PLAYING', 'PENDING_VERIFICATION', 'APPROVED', 'REJECTED', 'CANCELLED'
    created_by INTEGER REFERENCES users(id) NOT NULL,
    started_at TIMESTAMP WITH TIME ZONE,
    completed_at TIMESTAMP WITH TIME ZONE,
    verified_at TIMESTAMP WITH TIME ZONE,
    verified_by INTEGER REFERENCES users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 7. MATCH PLAYERS TABLE
CREATE TABLE IF NOT EXISTS match_players (
    id SERIAL PRIMARY KEY,
    match_id INTEGER REFERENCES matches(id) ON DELETE CASCADE NOT NULL,
    player_id INTEGER REFERENCES users(id) NOT NULL,
    side VARCHAR(10) NOT NULL, -- 'SIDE_A', 'SIDE_B'
    team_id INTEGER REFERENCES teams(id),
    player_rating_before DOUBLE PRECISION,
    player_rating_after DOUBLE PRECISION,
    rating_change DOUBLE PRECISION
);

-- 8. MATCH RESULTS TABLE
CREATE TABLE IF NOT EXISTS match_results (
    id SERIAL PRIMARY KEY,
    match_id INTEGER REFERENCES matches(id) ON DELETE CASCADE NOT NULL,
    winner_side VARCHAR(10) NOT NULL, -- 'SIDE_A', 'SIDE_B', 'DRAW'
    score_a INTEGER NOT NULL,
    score_b INTEGER NOT NULL,
    is_penalty_shootout BOOLEAN DEFAULT FALSE NOT NULL,
    penalty_score_a INTEGER,
    penalty_score_b INTEGER,
    submitted_by INTEGER REFERENCES users(id) NOT NULL,
    submitted_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    rejection_reason TEXT
);

-- 9. MATCH EVIDENCE TABLE
CREATE TABLE IF NOT EXISTS match_evidence (
    id SERIAL PRIMARY KEY,
    match_id INTEGER REFERENCES matches(id) ON DELETE CASCADE NOT NULL,
    uploaded_by INTEGER REFERENCES users(id) NOT NULL,
    file_url VARCHAR(500) NOT NULL,
    file_type VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 10. TEAM STATISTICS TABLE
CREATE TABLE IF NOT EXISTS team_statistics (
    id SERIAL PRIMARY KEY,
    team_id INTEGER REFERENCES teams(id) ON DELETE CASCADE UNIQUE NOT NULL,
    matches INTEGER DEFAULT 0 NOT NULL,
    wins INTEGER DEFAULT 0 NOT NULL,
    losses INTEGER DEFAULT 0 NOT NULL,
    draws INTEGER DEFAULT 0 NOT NULL,
    points INTEGER DEFAULT 0 NOT NULL,
    win_rate DOUBLE PRECISION DEFAULT 0.0 NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 11. ACHIEVEMENTS TABLE
CREATE TABLE IF NOT EXISTS achievements (
    id SERIAL PRIMARY KEY,
    name VARCHAR(100) UNIQUE NOT NULL,
    description VARCHAR(255) NOT NULL,
    icon VARCHAR(100) NOT NULL,
    requirement_type VARCHAR(50) NOT NULL,
    requirement_value INTEGER DEFAULT 1 NOT NULL
);

-- 12. PLAYER ACHIEVEMENTS TABLE
CREATE TABLE IF NOT EXISTS player_achievements (
    id SERIAL PRIMARY KEY,
    player_id INTEGER REFERENCES users(id) ON DELETE CASCADE NOT NULL,
    achievement_id INTEGER REFERENCES achievements(id) ON DELETE CASCADE NOT NULL,
    awarded_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT unique_player_achievement UNIQUE(player_id, achievement_id)
);

-- 13. AUDIT LOGS TABLE
CREATE TABLE IF NOT EXISTS audit_logs (
    id SERIAL PRIMARY KEY,
    actor_id INTEGER REFERENCES users(id),
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(50) NOT NULL,
    entity_id VARCHAR(50) NOT NULL,
    old_value TEXT,
    new_value TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- 14. ADMIN PERMISSIONS TABLE
CREATE TABLE IF NOT EXISTS admin_permissions (
    id SERIAL PRIMARY KEY,
    admin_id INTEGER REFERENCES users(id) ON DELETE CASCADE NOT NULL,
    permission VARCHAR(50) NOT NULL,
    enabled BOOLEAN DEFAULT TRUE NOT NULL
);

-- 15. SYSTEM SETTINGS TABLE
CREATE TABLE IF NOT EXISTS system_settings (
    id SERIAL PRIMARY KEY,
    key VARCHAR(100) UNIQUE NOT NULL,
    value VARCHAR(255) NOT NULL,
    description VARCHAR(255)
);

-- 16. TEAM REQUESTS TABLE
CREATE TABLE IF NOT EXISTS team_requests (
    id SERIAL PRIMARY KEY,
    player_id INTEGER REFERENCES users(id) ON DELETE CASCADE NOT NULL,
    team_name VARCHAR(100) NOT NULL,
    league VARCHAR(100),
    notes TEXT,
    status VARCHAR(20) DEFAULT 'PENDING' NOT NULL, -- 'PENDING', 'APPROVED', 'REJECTED'
    rejection_reason TEXT,
    reviewed_by INTEGER REFERENCES users(id),
    reviewed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

